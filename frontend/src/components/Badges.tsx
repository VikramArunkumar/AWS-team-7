/**
 * Status and provenance badges with clear, explicit labels.
 *
 * These make AI provenance unmistakable and ensure AI output is never shown as
 * a confirmed clinical fact: anything model-generated carries an "AI-generated"
 * tag and (while pending) a "Requires human review" tag.
 */

import type { RecommendationStatus, UrgencyLevel } from '../types.ts';

export function AiGeneratedBadge(): JSX.Element {
  return (
    <span className="badge badge-ai" title="Generated by Amazon Bedrock. Advisory only.">
      AI-generated
    </span>
  );
}

export function RequiresReviewBadge(): JSX.Element {
  return (
    <span className="badge badge-review" title="A human must review before any action is taken.">
      Requires human review
    </span>
  );
}

export function BedrockUnavailableBadge(): JSX.Element {
  return (
    <span className="badge badge-unavailable" title="AI processing failed; the original update is preserved.">
      Bedrock unavailable
    </span>
  );
}

export function StatusBadge({ status }: { status: RecommendationStatus }): JSX.Element {
  const label =
    status === 'approved' ? 'Human approved' : status === 'rejected' ? 'Rejected' : 'Pending review';
  return <span className={`badge badge-status-${status}`}>{label}</span>;
}

export function UrgencyBadge({ level }: { level: UrgencyLevel }): JSX.Element {
  return <span className={`badge badge-urgency-${level.toLowerCase()}`}>{level}</span>;
}
