import React, { useState } from 'react';
import { ArrowRight, BookOpen, FileText, TriangleAlert, ShieldCheck, Search, LoaderCircle } from 'lucide-react';
import { findPolicies, policyLibraryLabel } from './policies.js';

// Policy assistant (FR-26 to FR-29).
//
// Asks the CareBridge API (POST /policy/ask), which answers only from the
// Bedrock Knowledge Base and returns citations built from the documents it
// actually retrieved (FR-28), or found:false when nothing relevant exists
// (FR-29). If the backend reports the Knowledge Base is not configured, the
// assistant falls back to keyword-matching the local synthetic fixtures and
// labels that result as such; it never presents fixture matches as an AI or
// Knowledge Base answer.
export default function PolicyAssistant({ api, onAuthError }) {
  const [question, setQuestion] = useState('');
  const [busy, setBusy] = useState(false);
  // { question, source: 'kb' | 'local', found, answer, citations } | { question, error }
  const [result, setResult] = useState(null);

  const ask = async (event) => {
    event.preventDefault();
    const trimmed = question.trim();
    if (!trimmed || busy) return;
    setBusy(true);
    try {
      if (!api) throw Object.assign(new Error('no api'), { code: 'policy_unavailable' });
      const res = await api.askPolicy(trimmed);
      setResult({
        question: trimmed, source: 'kb', found: !!res.found, answer: res.answer ?? null,
        citations: Array.isArray(res.citations) ? res.citations : [],
      });
    } catch (err) {
      if (onAuthError?.(err)) return;
      if (err?.code === 'policy_unavailable') {
        const matches = findPolicies(trimmed);
        setResult({
          question: trimmed, source: 'local', found: matches.length > 0, answer: null,
          citations: matches.map((p) => ({ reference: p.reference, title: p.title, section: p.section, excerpt: p.summary })),
        });
      } else {
        setResult({ question: trimmed, error: err?.message || 'The policy assistant is unavailable. Try again shortly.' });
      }
    } finally {
      setBusy(false);
    }
  };

  const hasAnswer = result && !result.error && result.found;
  const noEvidence = result && !result.error && !result.found;
  const fromKb = result?.source === 'kb';

  return (
    <section className="panel policy-panel">
      <span className="policy-symbol"><BookOpen size={30} /></span>
      <span className="badge teal">Policy assistant</span>
      <h2>Reliable answers start with your policies.</h2>
      <p>
        Ask about facility downtime procedures. Answers are AI-generated from the synthetic facility
        policy library and cite the source documents. Verify against current facility policy before acting.
      </p>

      <form className="policy-input" onSubmit={ask}>
        <label className="sr-only" htmlFor="policy-question">Your question</label>
        <input
          id="policy-question"
          value={question}
          maxLength={500}
          onChange={(event) => setQuestion(event.target.value)}
          placeholder="How do I document care during an EHR outage?"
        />
        <button className="primary-button" type="submit" disabled={busy} aria-label="Ask the policy assistant">
          {busy ? <LoaderCircle size={18} className="auth-spinner" /> : <ArrowRight size={18} />}
        </button>
      </form>
      <small>Synthetic demonstration policies only. Not real clinical guidance.</small>

      {hasAnswer && (
        <div className="policy-answer" role="region" aria-label="Policy answer">
          {fromKb ? (
            <>
              <span className="eyebrow"><BookOpen size={12} /> AI-GENERATED ANSWER · VERIFY BEFORE ACTING</span>
              <article className="policy-result"><p>{result.answer}</p></article>
              <h3>Sources</h3>
            </>
          ) : (
            <span className="eyebrow"><BookOpen size={12} /> KEYWORD MATCH · {policyLibraryLabel.toUpperCase()}</span>
          )}
          {result.citations.map((c, i) => (
            <article className="policy-result" key={`${c.reference}-${i}`}>
              {!fromKb && <h3>{c.title}</h3>}
              {fromKb ? <p className="muted">“{c.excerpt}”</p> : <p>{c.excerpt}</p>}
              <div className="policy-citation">
                <FileText size={14} />
                <span>
                  <strong>{c.reference}</strong>
                  {c.section && <small>{c.section}</small>}
                </span>
              </div>
            </article>
          ))}
          <p className="policy-disclaimer">
            <ShieldCheck size={13} />
            {fromKb
              ? ' Generated by Amazon Bedrock from the retrieved policy documents above. Confirm the current procedure with your facility before acting.'
              : ' The policy Knowledge Base is not configured, so this is a local keyword match against fictional demo policies, not an AI answer.'}
          </p>
        </div>
      )}

      {noEvidence && (
        <div className="policy-empty" role="region" aria-label="No policy found">
          <TriangleAlert size={20} />
          <div>
            <strong>No relevant policy found</strong>
            <p>
              No policy document answered “{result.question}”. No answer or citation is shown rather
              than guessing. Try different wording, or consult your facility's policy directly.
            </p>
          </div>
        </div>
      )}

      {result?.error && (
        <div className="notice amber-notice" role="alert">
          <TriangleAlert size={16} /> {result.error}
        </div>
      )}

      {!result && (
        <div className="policy-hint">
          <Search size={14} />
          <span>Try: documentation, medications, handoff, escalation, or supplies.</span>
        </div>
      )}
    </section>
  );
}
